import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
let passed = 0;
function check(name, value) { assert.ok(value, name); passed++; console.log(`✓ ${name}`); }
try {
 const page = await browser.newPage({viewport:{width:1280,height:900}}), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8787');
 const pet=page.locator('#space-pet'), character=page.locator('.space-pet__character'), dock=page.locator('.space-pet-dock'), toggle=page.locator('.space-pet-toggle'), mode=page.locator('.space-pet__mode select');
 await page.locator('#space-pet[data-state="ready"]').waitFor();
 const size=await character.boundingBox();
 check('Desktop character is one third size',Math.abs(size.height-218/3)<.1 && Math.abs(size.width-206/3)<.1);
 check('No interaction, pause or minus buttons',await page.locator('[data-reaction], [data-action="pause"], [data-action="hide"], .space-pet__actions').count()===0);
 await character.click(); await character.dblclick(); await page.waitForTimeout(400);
 check('Clicks do not trigger effects',await pet.getAttribute('data-reaction')===null && await page.locator('.space-pet__particles').count()===0);
 const fixed=await dock.boundingBox(), before=await pet.boundingBox();
 await page.mouse.move(before.x+30,before.y+30);await page.mouse.down();await page.mouse.move(450,350,{steps:6});await page.mouse.up();
 const after=await pet.boundingBox();
 check('Character remains draggable',after.x<before.x-100);
 check('Mode and copyright stay fixed while dragging',JSON.stringify(await dock.boundingBox())===JSON.stringify(fixed));
 await toggle.click(); check('Whale button hides character',!(await pet.isVisible()));
 check('Whale and copyright remain available',await toggle.isVisible() && await page.locator('.space-pet__credit').isVisible());
 check('Toggle announces hidden state',await toggle.getAttribute('aria-expanded')==='false');
 await toggle.click(); check('Same whale button restores character',await pet.isVisible() && await toggle.getAttribute('aria-expanded')==='true');
 check('Restore preserves position',Math.abs((await pet.boundingBox()).x-after.x)<1);
 await mode.selectOption('follow');await page.mouse.click(12,400);await page.mouse.move(12,400);await page.waitForTimeout(600);
 check('Selected follow mode still works', (await pet.boundingBox()).x<after.x-5);
 check('Control dock does not follow movement',JSON.stringify(await dock.boundingBox())===JSON.stringify(fixed));
 await toggle.click();await page.reload();await toggle.waitFor();
 check('Hidden preference survives reload',!(await pet.isVisible()));
 await toggle.click();await mode.selectOption('stay');await page.setViewportSize({width:390,height:844});
 const mobile=await character.boundingBox(), mobileDock=await dock.boundingBox();
 check('Mobile character is one third size',Math.abs(mobile.height-178/3)<.1 && Math.abs(mobile.width-60)<.1);
 check('Mobile dock sits above navigation',mobileDock.x>=0 && mobileDock.x+mobileDock.width<=390 && mobileDock.y+mobileDock.height<=764);
 await character.focus();await page.keyboard.press('ArrowLeft');check('Arrow keys still move the character', (await pet.boundingBox()).x<mobile.x);
 await page.keyboard.press('Enter');check('Enter no longer triggers interactions',await pet.getAttribute('data-reaction')===null);
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(100);
 check('Reduced motion supported',await page.locator('.space-pet__sprite').evaluate(el=>getComputedStyle(el).animationName)==='none');
 await page.screenshot({path:'/tmp/dafeiyu-dock-mobile.png'});
 check('No browser errors',errors.length===0);
 console.log(`${passed} browser checks passed.`);
} finally { await browser.close(); }
